const { Pool } = require('pg');

const databaseUrl = process.env.DATABASE_URL;

if (!databaseUrl) {
  throw new Error('Falta configurar DATABASE_URL. Copia .env.example a .env y revisa la conexión.');
}

const pool = new Pool({
  connectionString: databaseUrl,
  ssl: process.env.DATABASE_SSL === 'true' ? { rejectUnauthorized: false } : undefined,
  max: Number.parseInt(process.env.DB_POOL_MAX || '10', 10),
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 5_000,
});

pool.on('error', (error) => {
  console.error('Error inesperado en una conexión inactiva de PostgreSQL:', error.message);
});

async function initializeDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS videojuegos (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      titulo VARCHAR(150) NOT NULL CHECK (length(trim(titulo)) > 0),
      genero VARCHAR(80) NOT NULL CHECK (length(trim(genero)) > 0),
      plataforma VARCHAR(100) NOT NULL CHECK (length(trim(plataforma)) > 0),
      desarrollador VARCHAR(120) NOT NULL CHECK (length(trim(desarrollador)) > 0),
      anio_lanzamiento SMALLINT NOT NULL CHECK (anio_lanzamiento BETWEEN 1950 AND 2100),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await pool.query(`
    INSERT INTO videojuegos (id, titulo, genero, plataforma, desarrollador, anio_lanzamiento)
    VALUES
      (1, 'The Legend of Zelda: Breath of the Wild', 'Acción y aventura', 'Nintendo Switch', 'Nintendo', 2017),
      (2, 'Minecraft', 'Sandbox', 'PC, consola y móvil', 'Mojang Studios', 2011),
      (3, 'God of War Ragnarök', 'Acción y aventura', 'PlayStation 4 y 5', 'Santa Monica Studio', 2022)
    ON CONFLICT (id) DO NOTHING
  `);

  await pool.query(`
    SELECT setval(
      pg_get_serial_sequence('videojuegos', 'id'),
      GREATEST(COALESCE((SELECT MAX(id) FROM videojuegos), 1), 1),
      EXISTS (SELECT 1 FROM videojuegos)
    )
  `);
}

module.exports = { pool, initializeDatabase };
