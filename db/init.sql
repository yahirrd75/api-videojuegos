CREATE TABLE IF NOT EXISTS videojuegos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(150) NOT NULL CHECK (length(trim(titulo)) > 0),
  genero VARCHAR(80) NOT NULL CHECK (length(trim(genero)) > 0),
  plataforma VARCHAR(100) NOT NULL CHECK (length(trim(plataforma)) > 0),
  desarrollador VARCHAR(120) NOT NULL CHECK (length(trim(desarrollador)) > 0),
  anio_lanzamiento SMALLINT NOT NULL CHECK (anio_lanzamiento BETWEEN 1950 AND 2100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

